-- Works on an empty database and on a hand-made `jobs` table from the first version of TaskForge.
CREATE TABLE IF NOT EXISTS jobs (
  id           uuid PRIMARY KEY,
  type         text NOT NULL,
  payload      jsonb,
  status       text NOT NULL,
  completed_at timestamptz
);

-- The old table was created by hand, so its column types are unknown. Normalise them.
DO $$
DECLARE
  item record;
  wanted text;
BEGIN
  FOR item IN
    SELECT conname FROM pg_constraint
    WHERE conrelid = 'jobs'::regclass AND contype = 'c'
      AND pg_get_constraintdef(oid) ILIKE '%status%'
  LOOP
    EXECUTE format('ALTER TABLE jobs DROP CONSTRAINT %I', item.conname);
  END LOOP;

  FOR item IN
    SELECT attname, format_type(atttypid, atttypmod) AS actual FROM pg_attribute
    WHERE attrelid = 'jobs'::regclass AND NOT attisdropped
      AND attname IN ('id', 'type', 'payload', 'status', 'created_at', 'completed_at')
  LOOP
    wanted := CASE item.attname
      WHEN 'id' THEN 'uuid'
      WHEN 'payload' THEN 'jsonb'
      WHEN 'created_at' THEN 'timestamp with time zone'
      WHEN 'completed_at' THEN 'timestamp with time zone'
      ELSE 'text'
    END;
    IF item.actual <> wanted THEN
      EXECUTE format('ALTER TABLE jobs ALTER COLUMN %I DROP DEFAULT', item.attname);
      EXECUTE format('ALTER TABLE jobs ALTER COLUMN %1$I TYPE %2$s USING %1$I::%2$s', item.attname, wanted);
    END IF;
  END LOOP;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS jobs_id_key ON jobs (id);

ALTER TABLE jobs
  ADD COLUMN IF NOT EXISTS seq             bigint GENERATED BY DEFAULT AS IDENTITY,
  ADD COLUMN IF NOT EXISTS priority        text NOT NULL DEFAULT 'normal' CHECK (priority IN ('high', 'normal', 'low')),
  ADD COLUMN IF NOT EXISTS attempts        integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS max_attempts    integer NOT NULL DEFAULT 3,
  ADD COLUMN IF NOT EXISTS run_at          timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN IF NOT EXISTS dispatched_at   timestamptz,
  ADD COLUMN IF NOT EXISTS lease_token     uuid,
  ADD COLUMN IF NOT EXISTS lease_until     timestamptz,
  ADD COLUMN IF NOT EXISTS worker          text,
  ADD COLUMN IF NOT EXISTS result          jsonb,
  ADD COLUMN IF NOT EXISTS error           text,
  ADD COLUMN IF NOT EXISTS idempotency_key text,
  ADD COLUMN IF NOT EXISTS created_at      timestamptz DEFAULT now(),
  ADD COLUMN IF NOT EXISTS started_at      timestamptz;

UPDATE jobs SET created_at = COALESCE(completed_at, now()) WHERE created_at IS NULL;
ALTER TABLE jobs ALTER COLUMN created_at SET DEFAULT now(), ALTER COLUMN created_at SET NOT NULL;

CREATE UNIQUE INDEX jobs_seq_key ON jobs (seq);
CREATE UNIQUE INDEX jobs_idempotency_key ON jobs (idempotency_key) WHERE idempotency_key IS NOT NULL;
CREATE INDEX jobs_dispatch_idx ON jobs (dispatched_at NULLS FIRST, run_at) WHERE status = 'pending';
CREATE INDEX jobs_lease_idx ON jobs (lease_until) WHERE status = 'processing';
CREATE INDEX jobs_status_seq_idx ON jobs (status, seq DESC);

CREATE TABLE job_events (
  id      bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  job_id  uuid NOT NULL REFERENCES jobs (id) ON DELETE CASCADE,
  kind    text NOT NULL,
  attempt integer NOT NULL DEFAULT 0,
  worker  text,
  detail  text,
  wait_ms integer,
  run_ms  integer,
  at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX job_events_job_idx ON job_events (job_id, id);
CREATE INDEX job_events_at_idx ON job_events (at);

CREATE TABLE workers (
  id              uuid PRIMARY KEY,
  name            text NOT NULL,
  pid             integer NOT NULL,
  concurrency     integer NOT NULL,
  active          uuid[] NOT NULL DEFAULT '{}',
  started_at      timestamptz NOT NULL DEFAULT now(),
  last_seen       timestamptz NOT NULL DEFAULT now(),
  crash_requested boolean NOT NULL DEFAULT false
);

-- Every transition writes an event in the same statement as the state change, and NOTIFY only
-- fires on commit, so the live stream can never show something that was rolled back.
CREATE FUNCTION taskforge_notify() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  PERFORM pg_notify('taskforge_events', json_build_object(
    'id', NEW.id, 'jobId', NEW.job_id, 'kind', NEW.kind, 'attempt', NEW.attempt,
    'worker', NEW.worker, 'detail', left(NEW.detail, 160), 'at', NEW.at,
    'type', left(j.type, 60), 'priority', j.priority
  )::text) FROM jobs j WHERE j.id = NEW.job_id;
  RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER job_events_notify AFTER INSERT ON job_events
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION taskforge_notify();
